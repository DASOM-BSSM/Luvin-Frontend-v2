/** 나이로 배경을 정한다. 서버가 하는 일을 흉내 낸다 — 20~23세는 시즌 시작 때 한 번 고른다. */
export function settingForAge(age: number, pick: number): SeasonSetting {
  if (age <= 19) return 'school';
  if (age <= 23) return pick < 0.5 ? 'campus' : 'cafe';
  return 'office';
}

